  program_id text not null references public.rehab_programs(id) on delete cascade,
  phase_no int not null,
  name text not null,
  typical_duration text,
  goal text not null,
  entry_criteria text not null,
  exit_criteria text not null,
  frequency text,
  running_guidance text,
  primary key (program_id, phase_no)
);
create table public.rehab_phase_exercises (
  program_id text not null,
  phase_no int not null,
  sort_order int not null,
  exercise_id text not null references public.exercises(id),
  dose text not null,
  notes text,
  primary key (program_id, phase_no, sort_order),
