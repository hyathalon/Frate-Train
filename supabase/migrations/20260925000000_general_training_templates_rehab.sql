-- Plan any session length: how many exercises, rounds and rest fit.
-- Mirrors the numbers in session_templates for 20/30/45/60 minutes.
create or replace function public.plan_session(p_method text, p_minutes int, p_level text default 'Beginner')
returns table (exercise_count int, rounds int, sets int, work_seconds int, change_seconds int, rest_seconds int,
               warmup_min int, cooldown_min int, estimated_min numeric, structure text)
language plpgsql immutable as $$
declare w int; c int; main numeric; wk int; tr int; rs int; st int; r int; n int; per numeric; cap int; lv text;
begin
  lv := case when p_level in ('Beginner','Intermediate','Advanced') then p_level else 'Beginner' end;
  if p_minutes <= 20 then w := 5; c := 2; elsif p_minutes <= 30 then w := 7; c := 3; else w := 10; c := 5; end if;
  if p_method = 'Mobility' then w := 0; c := 0; end if;
  main := p_minutes - w - c;
  if p_method = 'Circuit' then
    wk := case lv when 'Beginner' then 30 when 'Intermediate' then 40 else 45 end; tr := 60 - wk; rs := 120;
    r := case when main <= 30 then 3 else 4 end; per := (wk + tr) / 60.0;
    n := greatest(3, least(10, floor(((main + rs/60.0) / r - rs/60.0) / per)::int));
    return query select n, r, null::int, wk, tr, rs, w, c, round(w + r*n*per + (r-1)*rs/60.0 + c, 1),
      format('%s exercises × %s rounds, %s s work / %s s change-over, 2 min rest between rounds', n, r, wk, tr);
  elsif p_method = 'Strength' then
    wk := 45; tr := 15; rs := 120; st := 3; per := st*(2*wk+tr)/60.0 + (st-1)*rs/60.0 + 1;
    n := greatest(2, floor(main/per + 0.15)::int) * 2;
    return query select n, null::int, st, wk, tr, rs, w, c, round(w + (n/2)*per + c, 1),
      format('%s supersets (A1/A2 …), %s sets each, 2 min rest after each pair', n/2, st);
  elsif p_method = 'Plyometric' then
    wk := case lv when 'Advanced' then 12 else 10 end; tr := 30; rs := case lv when 'Beginner' then 60 when 'Intermediate' then 75 else 90 end;
    st := case lv when 'Advanced' then 4 else 3 end; cap := case lv when 'Intermediate' then 6 else 5 end;
    per := st*wk/60.0 + (st-1)*rs/60.0 + tr/60.0 + 0.5;
    n := greatest(3, least(cap, floor(main/per)::int));
    return query select n, null::int, st, wk, tr, rs, w, c, round(w + n*per + c, 1),
      format('%s drills, %s sets each, %s s rest between sets', n, st, rs);
  elsif p_method = 'Mobility' then
    n := greatest(4, floor(main/3.0)::int);
    return query select n, null::int, 1, 150, 30, 0, 0, 0, round(n*3.0, 1),
      format('%s mobility or recovery exercises, one after another', n);
  else
    raise exception 'Unknown method %', p_method;
  end if;
end $$;


