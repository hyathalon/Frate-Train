do $$
declare t text;
begin
  foreach t in array array['session_templates','session_template_slots','return_to_run_plans','return_to_run_steps'] loop
    execute format('create policy "%1$s read" on public.%1$I for select to authenticated using (true)', t);
    execute format('create policy "%1$s coach write" on public.%1$I for all to authenticated using (public.is_coach()) with check (public.is_coach())', t);
  end loop;
end $$;
-- Rehab: athletes only see programs a coach has marked Approved (after physio review).
create policy "rehab programs read" on public.rehab_programs for select to authenticated
  using (review_status = 'Approved' or public.is_coach());
create policy "rehab phases read" on public.rehab_phases for select to authenticated
  using (public.is_coach() or exists (select 1 from public.rehab_programs p where p.id = program_id and p.review_status = 'Approved'));
create policy "rehab exercises read" on public.rehab_phase_exercises for select to authenticated
  using (public.is_coach() or exists (select 1 from public.rehab_programs p where p.id = program_id and p.review_status = 'Approved'));
create policy "rehab programs coach write" on public.rehab_programs for all to authenticated using (public.is_coach()) with check (public.is_coach());
create policy "rehab phases coach write" on public.rehab_phases for all to authenticated using (public.is_coach()) with check (public.is_coach());
create policy "rehab exercises coach write" on public.rehab_phase_exercises for all to authenticated using (public.is_coach()) with check (public.is_coach());
